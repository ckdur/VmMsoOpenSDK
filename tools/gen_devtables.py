#!/usr/bin/env python3
"""Extract the static device capability tables from a vendor libvmmultmso.so.

The descriptor tables are factual hardware descriptions (channel counts,
sample rates, zoom/attenuator codes, DDS capabilities ...) that the device
does not transmit itself; the host picks one according to the model name
reported during the handshake. This script regenerates src/core/devtables.cpp.

usage: gen_devtables.py <libvmmultmso.so> > src/core/devtables.cpp
"""
import re, subprocess, sys

TABLES = ["mso10a", "mso10a_v2", "mso20a", "mso20a_v2", "mso20a_v3", "mso20a_v4",
          "mso20ll", "mso21a", "mso21a_v3", "mso21Plus_v1", "mso26", "mso41",
          "mso41_12", "mso41_20", "mdds10", "fg4100", "vb1000", "vb1000v2",
          "Iolab2000", "Iolab2000v2", "Iolab100", "card10", "hdwr30", "Kn2100",
          "kn8inch", "kd100", "kd250"]

lib = sys.argv[1]
data = open(lib, "rb").read()
segs = []
for l in subprocess.run(["readelf", "-lW", lib], capture_output=True, text=True).stdout.splitlines():
    p = l.split()
    if p and p[0] == "LOAD":
        segs.append((int(p[1], 16), int(p[2], 16), int(p[4], 16)))

def read(va, n):
    for off, v, fs in segs:
        if v <= va < v + fs:
            return data[off + va - v: off + va - v + n]
    raise KeyError(hex(va))

syms = {}
for l in subprocess.run(["nm", "-C", "-S", "--defined-only", lib], capture_output=True, text=True).stdout.splitlines():
    m = re.match(r"([0-9a-f]+) ([0-9a-f]+) [rRdD] (\S+)$", l)
    if m:
        syms.setdefault(m.group(3), (int(m.group(1), 16), int(m.group(2), 16)))

print("// Generated by tools/gen_devtables.py - device capability descriptor tables.")
print("#include \"devtables.h\"\n\nnamespace vmopen {\n")
for t in TABLES:
    a, n = syms[t]
    b = read(a, n)
    print("static const unsigned char tbl_%s[%d] = {" % (t, n))
    for i in range(0, n, 16):
        print("    " + ", ".join("0x%02x" % x for x in b[i:i + 16]) + ",")
    print("};\n")
print("const DevTable kDevTables[] = {")
for t in TABLES:
    print("    {\"%s\", tbl_%s, sizeof(tbl_%s)}," % (t, t, t))
print("    {nullptr, nullptr, 0},\n};\n")
print("const DevTable* FindDevTable(const char* name)\n{\n    for (const DevTable* t = kDevTables; t->name; t++)\n        if (std::strcmp(t->name, name) == 0)\n            return t;\n    return nullptr;\n}\n")
print("} // namespace vmopen")
